"""Execute the Lua backend with synthetic Call of Duty profile configs.
Optional developer dependency: pip install lupa. Game files are only read.
Award semantics follow maps/_endmission.gsc (CoD 4 mod tools): mis_difficulty holds one
digit per level (gameskill + 1), F.N.G. is always written as 4, Deep and Hard needs every
level except the epilogue at 3 or more, and the Veteran awards need 4 on every listed level.
"""
import hashlib
import json
from pathlib import Path
import tempfile
from lupa.luajit21 import LuaRuntime, lua_type

ROOT = Path(__file__).resolve().parent.parent
COD4 = json.loads((ROOT / 'source/games/cod4/game.json').read_text())
WAW = json.loads((ROOT / 'source/games/codwaw/game.json').read_text())


def from_lua(value):
    if lua_type(value) != 'table':
        return value
    pairs = dict(value.items())
    if pairs and set(pairs) == set(range(1, len(pairs) + 1)):
        return [from_lua(pairs[i]) for i in range(1, len(pairs) + 1)]
    return {str(k): from_lua(v) for k, v in pairs.items()}


def index_of(game, name):
    return next(i for i, a in enumerate(game['achievements']) if a['name'] == name)


def digits(game, default, **levels):
    names = [level[0] for level in game['levels']]
    return ''.join(str(levels.get(name, default)) for name in names)


def config(digits, intel=None):
    lines = ['// generated by Call of Duty', 'unbindall', 'seta cg_fov "65"',
             f'seta mis_difficulty "{digits.ljust(50, "0")}"', 'seta mis_01 "3"']
    if intel is not None:
        lines.append(f'seta cheat_points "{intel}"')
    return '\n'.join(lines) + '\n'


with tempfile.TemporaryDirectory() as temporary:
    base = Path(temporary)
    steam = base / 'Steam'
    (steam / 'steamapps').mkdir(parents=True)
    (steam / 'steamapps/appmanifest_7940.acf').write_text('"AppState" { "installdir" "Call of Duty 4" }')
    profile = steam / 'steamapps/common/Call of Duty 4/players/profiles/Player1'
    profile.mkdir(parents=True)
    cfg = profile / 'config.cfg'
    cfg.write_text(config('41'))
    local = base / 'Local'
    waw_profile = local / 'Activision/CoDWaW/players/profiles/Player1'
    waw_profile.mkdir(parents=True)
    (waw_profile / 'config.cfg').write_text(config('1'))
    settings, writes = {}, []

    lua = LuaRuntime(unpack_returned_tuples=True)
    lua.execute('package.path = ... .. ";" .. package.path', str(ROOT / 'backend/?.lua'))

    def set_config(key, value):
        settings[key] = from_lua(value)
        writes.append(key)
        return True

    def join(*parts):
        return str(Path(parts[0]).joinpath(*(p.replace('\\', '/') for p in parts[1:])))

    def list_dir(path):
        directory = Path(path)
        entries = []
        for item in sorted(directory.iterdir()) if directory.is_dir() else []:
            entries.append(lua.table_from({'path': str(item), 'name': item.name,
                'is_file': item.is_file(), 'is_directory': item.is_dir(),
                'is_symlink': item.is_symlink(), 'size': item.stat().st_size}))
        return lua.table_from(entries)

    modules = {
        'millennium': lua.table_from({'ready': lambda: True, 'steam_path': lambda: str(steam),
            'config': lua.table_from({'get': lambda k: None, 'set': set_config})}),
        'fs': lua.table_from({'list': list_dir, 'join': join, 'filename': lambda p: Path(p).name,
            'is_file': lambda p: Path(p).is_file(), 'is_directory': lambda p: Path(p).is_dir(),
            'parent_path': lambda p: str(Path(p).parent), 'last_write_time': lambda p: int(Path(p).stat().st_mtime)}),
        'json': lua.table_from({'encode': lambda v: json.dumps(from_lua(v)), 'decode': lambda v: lua.table_from(json.loads(v))}),
    }
    for name, module in modules.items():
        lua.globals().package.loaded[name] = module
    lua.execute('clock=100; os.time=function() return clock end')
    lua.globals().os.getenv = lambda name: str(local) if name == 'LOCALAPPDATA' else None
    # Every pack now has a detector; Thrillville is turned back into a manual game here so the
    # manual-game paths (pasted folders, the pack's save reader) stay covered.
    lua.execute("local games = require('games'); for _, g in ipairs(games) do if g.appId == 6080 then g.detector, g.rules = nil, nil end end")
    backend = lua.execute((ROOT / 'backend/main.lua').read_text())
    backend['on_load']()

    def tick(app_id, method='GetTrackerState', **extra):
        lua.globals().clock += 2
        payload = json.dumps({'appId': app_id, **extra})
        return json.loads(lua.globals()[method](lua.table_from({'payload': payload})))

    def settle(app_id):
        tick(app_id)
        return tick(app_id)

    state = settle(7940)
    assert state['status'] == 'watching', state
    assert state['saveFileName'] == 'config.cfg'
    got = set(map(int, state['progress']))
    assert got == {index_of(COD4, 'Earn a Winged Dagger'), index_of(COD4, 'Make the Jump')}, got
    # Profile names are listed for the settings panel, but no full path leaves the backend.
    assert str(base) not in json.dumps(state)
    assert 'Player1' not in json.dumps({k: v for k, v in state.items() if k != 'availableSaves'})
    assert 'autoProgress_7940_v1' in writes
    print('PASS CoD 4 profile found through the Steam library; finished missions unlock, nothing else does')

    digest = hashlib.sha256(cfg.read_bytes()).hexdigest()
    cfg.write_text(config('4444', intel=14))
    state = tick(7940)
    assert state['status'] == 'stabilizing'
    state = tick(7940)
    got = set(map(int, state['progress']))
    assert index_of(COD4, 'The Package') in got and index_of(COD4, 'The Rescue') in got
    assert index_of(COD4, 'Look Sharp') not in got
    assert state['counts'][str(index_of(COD4, 'Look Sharp'))] == {'have': 14, 'need': 15, 'label': 'Enemy intel'}
    cfg.write_text(config('4444', intel=15))
    got = set(map(int, settle(7940)['progress']))
    assert index_of(COD4, 'Look Sharp') in got and index_of(COD4, 'Eyes and Ears') not in got
    print('PASS Veteran digits and intel counter (14 of 15 shows progress, 15 unlocks)')

    # Every level but the epilogue on Hardened: Deep and Hard and Win the War, but no Veteran pairs.
    cfg.write_text(config('4' + '3' * 19 + '0', intel=30))
    state = settle(7940)
    got = set(map(int, state['progress']))
    for name in ('Deep and Hard', 'Win the War', 'Desperate Measures', 'Eyes and Ears'):
        assert index_of(COD4, name) in got, name
    for name in ('The Bog', 'The Fourth Horseman', 'Mile High Club'):
        assert index_of(COD4, name) not in got, name
    # The Bog needs both The Bog and War Pig on Veteran.
    cfg.write_text(config(digits(COD4, 3, killhouse=4, bog_a=4, airplane=0), intel=30))
    state = settle(7940)
    assert index_of(COD4, 'The Bog') not in set(map(int, state['progress']))
    assert state['counts'][str(index_of(COD4, 'The Bog'))]['have'] == 1
    cfg.write_text(config(digits(COD4, 3, killhouse=4, bog_a=4, bog_b=4, airplane=4), intel=30))
    got = set(map(int, settle(7940)['progress']))
    assert index_of(COD4, 'The Bog') in got and index_of(COD4, 'Mile High Club') in got
    print('PASS Deep and Hard ignores the epilogue; two-level Veteran awards need both levels')

    unrelated = profile.parent / 'Other'
    unrelated.mkdir()
    (unrelated / 'config.cfg').write_text('seta cg_fov "80"\n')
    try:
        tick(7940, 'SetSavePath', path=str(unrelated / 'config.cfg'))
        raise AssertionError('A config without campaign progress must be rejected')
    except Exception as error:
        assert 'mis_difficulty' in str(error)
    state = tick(7940, 'SetSavePath', path=str(profile.parent))
    assert state['selectionNote'] and settings['savePath_7940_v1'] == str(cfg)
    assert hashlib.sha256((unrelated / 'config.cfg').read_bytes()).hexdigest()
    print('PASS a profiles folder resolves to the campaign config; configs without progress are refused')

    state = settle(10090)
    assert state['status'] == 'watching', state
    assert set(map(int, state['progress'])) == {index_of(WAW, "Carlson's Raiders")}
    print('PASS World at War profile found under LOCALAPPDATA\\Activision\\CoDWaW')

    # Shape of a real 100% Regular profile: 15 missions at 2, all 13 Death Cards.
    (waw_profile / 'config.cfg').write_text(config('2' * 15, intel=12))
    state = settle(10090)
    assert index_of(WAW, 'Grave Robber') not in set(map(int, state['progress']))
    assert state['counts'][str(index_of(WAW, 'Grave Robber'))]['have'] == 12
    (waw_profile / 'config.cfg').write_text(config('2' * 15, intel=13))
    got = set(map(int, settle(10090)['progress']))
    expected = {"Carlson's Raiders", 'Stormed Peleliu', 'The Last Stand', 'Stabbed in the Heart', 'War Hero', 'Grave Robber'}
    assert got == {index_of(WAW, name) for name in expected}, got
    print('PASS World at War 100% Regular run: story and Death Cards unlock, Hardened and Veteran do not')

    manual = tick(6080)
    assert manual['status'] == 'manual' and manual['progress'] == {}
    try:
        tick(6080, 'SetSavePath', path='C:/x')
        raise AssertionError('Manual games have no save selection')
    except Exception as error:
        assert 'no automatic tracking' in str(error)
    try:
        tick(1234)
        raise AssertionError('Unknown games must be rejected')
    except Exception as error:
        assert 'Unknown game' in str(error)
    print('PASS manual-only games never read files; unknown app IDs are rejected')

print('All Call of Duty detector tests passed.')
