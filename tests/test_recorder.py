"""Record mode: snapshot a save folder, change it the way a game would, and check that the
report puts the change that matches the achievement first. Runs main.lua from a copy of
the plugin folder, the way Millennium loads it. Optional developer dependency: pip install lupa.
"""
import hashlib
import json
from pathlib import Path
import random
import shutil
import struct
import tempfile
from lupa.luajit21 import LuaRuntime, lua_type
from fable_fixture import herosave

ROOT = Path(__file__).resolve().parent.parent
PACKS = {slug: json.loads((ROOT / f'source/games/{slug}/game.json').read_text()) for slug in ('fable3', 'cod4', 'thrillville-otr')}


def from_lua(value):
    if lua_type(value) != 'table':
        return value
    pairs = dict(value.items())
    if pairs and set(pairs) == set(range(1, len(pairs) + 1)):
        return [from_lua(pairs[i]) for i in range(1, len(pairs) + 1)]
    return {str(k): from_lua(v) for k, v in pairs.items()}


def achievement(slug, name):
    index, a = next((i, a) for i, a in enumerate(PACKS[slug]['achievements']) if a['name'] == name)
    return {'index': index, 'name': a['name'], 'detail': a['detail']}


def cfg(mission, intel):
    return f'// generated by Call of Duty\nseta cg_fov "65"\nseta cheat_points "{intel}"\nseta mis_difficulty "{mission.ljust(50, "0")}"\nseta mis_01 "3"\n'


def digest(folder):
    return {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(folder.rglob('*')) if p.is_file()}


with tempfile.TemporaryDirectory() as temporary:
    base = Path(temporary)
    plugin = base / 'plugins/steam-custom-achievements'
    shutil.copytree(ROOT / 'backend', plugin / 'backend')
    recordings = plugin / 'recordings'
    recordings.mkdir()
    temp = base / 'Temp'
    temp.mkdir()
    steam = base / 'Steam'
    (steam / 'steamapps').mkdir(parents=True)
    (steam / 'steamapps/appmanifest_7940.acf').write_text('"AppState" { "installdir" "Call of Duty 4" }')
    cod_profile = steam / 'steamapps/common/Call of Duty 4/players/profiles/Player1'
    (cod_profile / 'save').mkdir(parents=True)
    (cod_profile / 'config.cfg').write_text(cfg('4', 3))
    (cod_profile / 'save/killhouse.svg').write_bytes(b'\x01' * 300)
    fable = base / 'User/Saved Games/Lionhead Studios/Fable 3/1122334400000000'
    fable.mkdir(parents=True)
    hero = fable / 'hero1autosave_herosave.bin'
    hero.write_bytes(herosave({'STAT_NUM_COLLECTED_GNOMES': 49, 'STAT_KILLS_MELEE': 120}))
    (fable / 'chaptersave.bin').write_text('<chapter>3</chapter>')
    thrill = base / 'Documents/Thrillville'
    thrill.mkdir(parents=True)
    park = bytearray(random.Random(3).randbytes(512))
    struct.pack_into('<I', park, 0x40, 19)
    (thrill / 'park1.sav').write_bytes(park)
    (thrill / 'options.ini').write_text('volume=7\n')

    lua = LuaRuntime(unpack_returned_tuples=True)
    lua.execute('package.path = ... .. ";" .. package.path', str(plugin / 'backend/?.lua'))

    def join(*parts):
        return str(Path(parts[0]).joinpath(*(p.replace('\\', '/') for p in parts[1:])))

    def list_dir(path):
        directory = Path(path)
        entries = []
        for item in sorted(directory.iterdir()) if directory.is_dir() else []:
            entries.append(lua.table_from({'path': str(item), 'name': item.name,
                'is_file': item.is_file(), 'is_directory': item.is_dir(),
                'is_symlink': item.is_symlink(), 'size': item.stat().st_size}))
        return lua.table_from(entries)

    modules = {
        'millennium': lua.table_from({'ready': lambda: True, 'steam_path': lambda: str(steam),
            'config': lua.table_from({'get': lambda k: None, 'set': lambda k, v: True})}),
        'fs': lua.table_from({'list': list_dir, 'join': join, 'filename': lambda p: Path(p).name,
            'is_file': lambda p: Path(p).is_file(), 'is_directory': lambda p: Path(p).is_dir(),
            'parent_path': lambda p: str(Path(p).parent), 'last_write_time': lambda p: int(Path(p).stat().st_mtime)}),
        'json': lua.table_from({'encode': lambda v: json.dumps(from_lua(v)), 'decode': lambda v: lua.table_from(json.loads(v))}),
    }
    for name, module in modules.items():
        lua.globals().package.loaded[name] = module
    env = {'USERPROFILE': str(base / 'User'), 'TEMP': str(temp)}
    lua.globals().os.getenv = lambda name: env.get(name)
    # Every pack now has a detector; Thrillville is turned back into a manual game here so the
    # manual-game paths (pasted folders, the pack's save reader) stay covered.
    lua.execute("local games = require('games'); for _, g in ipairs(games) do if g.appId == 6080 then g.detector, g.rules = nil, nil end end")
    backend = lua.eval('dofile')(str(plugin / 'backend/main.lua'))
    backend['on_load']()

    def call(method, app_id, **extra):
        return json.loads(lua.globals()[method](lua.table_from({'payload': json.dumps({'appId': app_id, **extra})})))

    # Fable III: one gnome short, smash the last one.
    originals = digest(fable)
    gnomes = achievement('fable3', 'Gnome Invasion')
    started = call('StartRecording', 105400, **gnomes)
    assert started['recording'] and started['folderName'] == '1122334400000000' and started['files'] == 2, started
    hero.write_bytes(herosave({'STAT_NUM_COLLECTED_GNOMES': 50, 'STAT_KILLS_MELEE': 121}))
    report = call('FinishRecording', 105400)
    assert [f['name'] for f in report['files']] == ['hero1autosave_herosave.bin'], report['files']
    stats = report['files'][0]
    assert stats['kind'] == 'hero statistics'
    assert stats['findings'][0] == {'where': 'STAT_NUM_COLLECTED_GNOMES', 'old': 49, 'new': 50, 'verdict': 'match'}, stats['findings']
    assert {'where': 'STAT_KILLS_MELEE', 'old': 120, 'new': 121} in stats['findings']
    assert report['targets'] == [50] and report['matches'] == 1
    assert report['rule'] == 'unlocked by the plugin', report['rule']
    assert report['savedTo'] == str(recordings) and report['savedFiles'] == 4, report
    text = next(recordings.glob('*Gnome Invasion report.txt')).read_text()
    assert 'STAT_NUM_COLLECTED_GNOMES: 49 -> 50  <== matches the achievement' in text, text
    assert next(recordings.glob('*before hero1autosave_herosave.bin')).read_bytes() != hero.read_bytes()
    assert next(recordings.glob('*after hero1autosave_herosave.bin')).read_bytes() == hero.read_bytes()
    print('PASS Fable III: the gnome counter reaching 50 is listed first, the plugin rule agrees, copies are saved')

    # CoD 4: a profile config is text; dvars are paired line by line.
    look = achievement('cod4', 'Look Sharp')
    call('StartRecording', 7940, **look)
    (cod_profile / 'config.cfg').write_text(cfg('41', 4))
    report = call('FinishRecording', 7940)
    [config] = [f for f in report['files'] if f['name'] == 'config.cfg']
    assert config['kind'] == 'text'
    first = config['findings'][0]
    assert first['where'] == 'seta cheat_points' and first['verdict'] == 'rising', config['findings']
    assert any(f['where'] == 'seta mis_difficulty' and f['new'].startswith('seta mis_difficulty "41') for f in config['findings'])
    assert report['rule'] == 'not yet: 4 / 15 Enemy intel', report['rule']
    print('PASS CoD 4: config.cfg lines are paired by dvar; intel counting toward 15 is flagged')

    # Thrillville has no detector: the folder is pasted and binary integers are decoded.
    karting = achievement('thrillville-otr', 'Karting Krazy')
    try:
        call('StartRecording', 6080, **karting)
        raise AssertionError('Manual games need a folder')
    except Exception as error:
        assert 'Paste the folder' in str(error), error
    try:
        call('FinishRecording', 6080)
        raise AssertionError('Finishing before starting must fail')
    except Exception as error:
        assert 'Nothing is being recorded' in str(error)
    before_hashes = digest(thrill)
    call('StartRecording', 6080, folder=f'"{thrill}"', **karting)
    assert digest(thrill) == before_hashes, 'starting a recording never changes game files'
    struct.pack_into('<I', park, 0x40, 20)
    park[0x100] ^= 0xFF
    (thrill / 'park1.sav').write_bytes(park)
    shutil.rmtree(recordings)
    report = call('FinishRecording', 6080)
    [save] = report['files']
    assert save['name'] == 'park1.sav' and save['kind'] == 'binary' and save['changedRanges'] == 2
    assert save['findings'][0] == {'where': 'offset 0x40 (u8)', 'old': 19, 'new': 20, 'verdict': 'match'}, save['findings']
    assert 'rule' not in report
    assert report['savedTo'] == str(temp), 'without a recordings folder, copies go to the temp folder'
    assert len(list(temp.glob('*Karting Krazy*'))) == 4
    print('PASS Thrillville: pasted folder, binary counter 19 -> 20 matches "1st in 20 races"; temp-folder fallback')

    # Narrowing over three recordings, like a RetroAchievements memory search.
    def change(**offsets):
        for offset, value in offsets.items():
            park[int(offset[1:], 16)] = value
        (thrill / 'park1.sav').write_bytes(park)
    park[0x40], park[0x80], park[0x100] = 20, 100, 5
    (thrill / 'park1.sav').write_bytes(park)
    call('StartRecording', 6080, folder=str(thrill), narrow=False, **karting)  # narrow=False starts a fresh search
    change(x40=21, x80=150, x100=9)                   # won a race; play time and something else moved too
    first = call('FinishRecording', 6080)['narrowing']
    assert first['passes'] == 1 and first['remaining'] == 3, first
    assert call('StartRecording', 6080, folder=str(thrill), narrow=True, **karting)['previousPasses'] == 1
    change(x80=170)                                   # played without winning: play time is ruled out
    second = call('FinishRecording', 6080, noProgress=True)
    assert second['noProgress'] and second['narrowing']['remaining'] == 2, second['narrowing']
    call('StartRecording', 6080, folder=str(thrill), narrow=True, **karting)
    change(x40=22, x80=200)                           # won again
    third = call('FinishRecording', 6080)['narrowing']
    assert third['passes'] == 3 and third['progressPasses'] == 2 and third['remaining'] == 1, third
    assert third['candidates'] == [{'file': 'park1.sav', 'where': 'offset 0x40 (u8)', 'values': [20, 21, 22]}], third
    text = sorted(temp.glob('*report.txt'))[-1].read_text()
    assert 'After 3 recordings (2 with progress): 1 values changed the same way every time.' in text, text
    fresh = call('StartRecording', 6080, folder=str(thrill), narrow=False, **karting)
    assert fresh['previousPasses'] == 0
    call('CancelRecording', 6080)
    print('PASS narrowing: progress, no-progress and progress recordings leave only the race counter 20 -> 21 -> 22')

    # Nothing changed: an empty report, not an error.
    call('StartRecording', 6080, folder=str(thrill), **karting)
    report = call('FinishRecording', 6080)
    assert not report['files'] and report['matches'] == 0  # an empty Lua table may encode as {}
    call('StartRecording', 6080, folder=str(thrill), **karting)
    assert call('CancelRecording', 6080)['recording'] is False
    assert digest(fable) != originals and digest(thrill)
    print('PASS no change gives an empty report; Cancel discards the snapshot')

print('All record mode tests passed.')
